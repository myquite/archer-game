const svgCache = new Map();

// Compile a 14x14 pixel matrix into a crisp 16x16 SVG with automatic 1px #0c0714 outline
function compileIconSvg(name) {
  if (svgCache.has(name)) return svgCache.get(name);
  const grid = GRIDS[name] || GRIDS.emblem_bow;

  // Trim empty rows/cols around sprite to auto-center it cleanly inside 16x16!
  let minX = 14, maxX = -1, minY = 14, maxY = -1;
  for (let y = 0; y < grid.length; y++) {
    const row = grid[y];
    for (let x = 0; x < row.length; x++) {
      if (row[x] !== '.') {
        if (x < minX) minX = x;
        if (x > maxX) maxX = x;
        if (y < minY) minY = y;
        if (y > maxY) maxY = y;
      }
    }
  }
  if (maxX < minX) { minX = 0; maxX = 0; minY = 0; maxY = 0; }

  const w = maxX - minX + 1;
  const h = maxY - minY + 1;
  const offX = Math.floor((16 - w) / 2) - minX;
  const offY = Math.floor((16 - h) / 2) - minY;

  const filled = new Map();
  for (let y = minY; y <= maxY; y++) {
    for (let x = minX; x <= maxX; x++) {
      const ch = grid[y][x];
      if (ch !== '.' && PAL[ch]) {
        filled.set(`${x + offX},${y + offY}`, PAL[ch]);
      }
    }
  }

  // 4-connected 1px #0c0714 outline pass
  const outlines = [];
  const dirs = [[1, 0], [-1, 0], [0, 1], [0, -1]];
  const seenOut = new Set();
  for (const key of filled.keys()) {
    const [x, y] = key.split(',').map(Number);
    for (const [dx, dy] of dirs) {
      const nx = x + dx;
      const ny = y + dy;
      const nk = `${nx},${ny}`;
      if (nx >= 0 && nx < 16 && ny >= 0 && ny < 16 && !filled.has(nk) && !seenOut.has(nk)) {
        seenOut.add(nk);
        outlines.push(`<rect x="${nx}" y="${ny}" width="1" height="1" fill="${OUTLINE}"/>`);
      }
    }
  }

  const rects = [];
  for (const [key, col] of filled.entries()) {
    const [x, y] = key.split(',').map(Number);
    rects.push(`<rect x="${x}" y="${y}" width="1" height="1" fill="${col}"/>`);
  }

  const svg = `<svg class="px-ico" viewBox="0 0 16 16" shape-rendering="crispEdges" aria-hidden="true">${outlines.join('')}${rects.join('')}</svg>`;
  svgCache.set(name, svg);
  return svg;
}

export function pxIcon(name, size = 16, extraClass = '') {
  const base = compileIconSvg(name);
  return `<span class="px-ico-wrap ${extraClass}" style="width:${size}px;height:${size}px">${base}</span>`;
}
